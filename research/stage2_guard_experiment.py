#!/usr/bin/env python
r"""Stage-2-LITE experiment (docs/SESSION_MEMORY_ROADMAP.md §6, gate OPEN).

QUESTION: does the shipped additive-bias guard rewording reduce the destructive-migration
(orphan) rate vs the old "migrate to the new design" guard?

NON-CIRCULAR: the migration is performed by an SLM (the thing under test — the guard text
nudges it), but the OUTCOME is judged by REAL pytest on the oracle fixture
(research/_oracle_groundtruth.py's `kwarg-removed-destructive` before-code + test), NEVER by an
SLM judge. The migrator sees the test NAME (as the live guard surfaces it), never the test BODY.

WHAT IS / ISN'T isolated (honest framing — code-review):
  - This compares the SHIPPED reworded guard vs the OLD guard — the real deployed A/B.
  - It is NOT a clean "framing-only" isolation: the new guard also adds more explicit
    preservation instructions and is longer, so a win means "the reworded guard helps",
    not "the additive *framing* alone is the sole causal variable".
  - `new` is generated by calling the LIVE refactor_guard_checklist (so it can never drift
    from production); `old` is the frozen pre-reword baseline (= origin/main's output).

SCORING (per trial): SLM returns the new lib.py.
  - empty / no extractable code  -> INVALID (a failed/empty completion is NOT a data point).
  - pytest infra error/timeout   -> INVALID.
  - else write lib.py + the fixture test -> pytest:
      test_green (rc==0) = connect_timeout PRESERVED (additive / correct migrate)
      test_red           = ORPHANED (kwarg dropped) OR broken code — `compiles` separates these,
                           so we also report a compiling-only rate (preservation among trials
                           that produced importable code).
METRIC = green rate over VALID trials (+ a compiling-only rate). Pre-registered hypothesis:
  green(new) > green(old), and ideally green(old) <= green(none) <= green(new).

NOTE on truncation: the live guard places the additive directive FIRST so GUARD_MAX_CHARS can't
drop it; this 1-contract experiment never hits the cap — the multi-contract truncation case is
covered deterministically by test_guard_framing_survives_many_contracts in _test_stage0_fixes.py.

Cost: N*3 small completions (default gpt-5.4-mini, ~cents). A tempdir per trial; read-only otherwise.
Usage:  python research/stage2_guard_experiment.py [N=12] [model=gpt-5.4-mini]
"""
from __future__ import annotations

import re
import subprocess
import sys
import tempfile
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
import _oracle_groundtruth as og  # noqa: E402  (before-code + test + the hardened _pytest)

# Reuse the oracle's kwarg fixture as the migration scenario (same before-code + test).
_CASE = next(c for c in og.ORPHAN_CASES if c["id"] == "kwarg-removed-destructive")
BEFORE_LIB = _CASE["before"]["lib.py"]
TEST_LIB = _CASE["before"]["test_lib.py"]

TASK = ("Refactor `make_client` so its timeout settings (timeout, connect_timeout) are configured "
        "through a single new `ResilienceConfig` dataclass.")


def _shipped_new_guard() -> str:
    """The REAL shipped `new` guard text — generated from the live refactor_guard_checklist so the
    experiment can NEVER drift from production. Seeds a 1-contract ledger matching the fixture's
    surfaced contract (connect-timeout, locked by test_connect_timeout_kwarg)."""
    import memory_ledger as ml
    d = tempfile.mkdtemp(prefix="s2guard_")
    try:
        ml.clear_ledger(d)
        ledger = ml.load_ledger(d)
        ml.merge_contracts(ledger, [{
            "feature": "connect-timeout",
            "contract": "make_client exposes a connect_timeout keyword argument.",
            "tests": ["test_connect_timeout_kwarg"],
        }], turn=1)
        ml.save_ledger(d, ledger)
        return ml.refactor_guard_checklist(
            d, "refactor make_client into a ResilienceConfig dataclass", None)
    finally:
        try:
            __import__("memory_ledger").clear_ledger(d)
        except Exception:
            pass


# `old` = the FROZEN pre-reword baseline (= origin/main's refactor_guard_checklist output:
# old header, "to keep or migrate" test label, framing appended LAST). Hardcoded on purpose — it
# is a historical reference that no longer exists in the code. `new` is generated live (above).
GUARD_OLD = (
    "[MEMORY — prior contracts you MUST preserve or intentionally migrate]\n"
    "- connect-timeout: make_client exposes a connect_timeout keyword argument.\n"
    "    tests/call-sites to keep or migrate: test_connect_timeout_kwarg\n"
    "This turn is a refactor/migration: do NOT silently drop the above — migrate their "
    "call-sites + tests to the new design, or explicitly state why each is removed."
)
ARMS = ("none", "old", "new")


def _prompt(guard: str, i: int) -> str:
    g = ("\n" + guard + "\n") if guard else "\n"
    return (
        "You are refactoring a small Python module. Current lib.py:\n\n"
        "```python\n" + BEFORE_LIB + "```\n\n"
        "TASK (attempt {0}): {1}\n".format(i, TASK) + g +
        "\nReturn ONLY the complete new contents of lib.py inside one ```python code block — "
        "no prose, no test file."
    )


_FENCE_PY = re.compile(r"```python\s*(.*?)```", re.S)
_FENCE_ANY = re.compile(r"```[a-zA-Z0-9+_-]*\s*(.*?)```", re.S)


def _extract_code(text: str) -> str:
    """Prefer a ```python block (the instructed format); fall back to any fence, then raw text."""
    if not text:
        return ""
    m = _FENCE_PY.search(text) or _FENCE_ANY.search(text)
    return (m.group(1) if m else text).strip()


def _compiles(code: str) -> bool:
    try:
        compile(code, "lib.py", "exec")
        return True
    except Exception:
        return False


def _score(code: str) -> tuple[bool, bool | None]:
    """(compiles, test_green). test_green None = pytest infra error/timeout (invalid trial).
    Narrow except (matches the oracle's intent): a programming bug here crashes loudly."""
    comp = _compiles(code)
    with tempfile.TemporaryDirectory() as d:
        root = Path(d)
        (root / "lib.py").write_text(code, encoding="utf-8")
        (root / "test_lib.py").write_text(TEST_LIB, encoding="utf-8")
        try:
            green = og._pytest(root)
        except (subprocess.SubprocessError, OSError):
            return comp, None
    return comp, green


def run(n: int, model: str) -> None:
    import os
    from prpt.judges import OpenAiJudge
    if not os.environ.get("OPENAI_API_KEY"):
        try:
            from prpt.core.dotenv import load_dotenv
            import prpt
            root = Path(prpt.__file__).resolve().parent.parent  # editable-install root (B:/LLM) holds .env
            load_dotenv(root / ".env")
        except Exception as e:
            print("[env] load_dotenv failed: {0}".format(e), file=sys.stderr)
    if not os.environ.get("OPENAI_API_KEY"):
        sys.exit("OPENAI_API_KEY not set (env + prpt-root/.env). Aborting — no migrator.")

    guard = {"none": "", "old": GUARD_OLD, "new": _shipped_new_guard()}
    judge = OpenAiJudge(model=model)
    probe_text, _pc, _ = judge("Reply with the single word: ok")
    if not (probe_text or "").strip():
        sys.exit("Migrator probe returned EMPTY (model={0}). Check the model name / API access.".format(model))

    print("Stage-2-lite guard experiment  (model={0}, N={1}/arm, oracle=kwarg fixture)".format(model, n))
    print("=" * 84)
    summary = {}
    total_cost = 0.0
    for arm in ARMS:
        green = comp = comp_green = invalid = valid = 0
        for i in range(1, n + 1):
            text, cost, _ = judge(_prompt(guard[arm], i))
            total_cost += float(cost or 0.0)
            code = _extract_code(text)
            if not code.strip():
                invalid += 1
                print("  {0:4s} t{1:<2} INVALID (empty / no extractable code)".format(arm, i))
                continue
            c, g = _score(code)
            if g is None:
                invalid += 1
                print("  {0:4s} t{1:<2} INVALID (pytest infra error)".format(arm, i))
                continue
            valid += 1
            comp += int(c)
            if g:
                green += 1
                if c:
                    comp_green += 1
            print("  {0:4s} t{1:<2} compiles={2} test_green={3}".format(arm, i, int(c), g))
        rate = (green / valid) if valid else None
        comp_rate = (comp_green / comp) if comp else None
        summary[arm] = {"green": green, "valid": valid, "compiles": comp,
                        "comp_green": comp_green, "rate": rate, "comp_rate": comp_rate,
                        "invalid": invalid}
        rs = "n/a" if rate is None else "{0:.2f}".format(rate)
        print("  -> {0}: green {1}/{2} = {3}  (compiling-only {4}/{5}; invalid {6})".format(
            arm, green, valid, rs, comp_green, comp, invalid))

    print("\n" + "=" * 84)
    print("RESULT — green (connect_timeout-preserved) rate per arm [over VALID trials]:")
    for arm in ARMS:
        s = summary[arm]
        rs = "n/a" if s["rate"] is None else "{0:.2f}".format(s["rate"])
        cs = "n/a" if s["comp_rate"] is None else "{0:.2f}".format(s["comp_rate"])
        print("  {0:4s}: {1}  (compiling-only {2}; green {3}/{4}, invalid {5})".format(
            arm, rs, cs, s["green"], s["valid"], s["invalid"]))

    g = {a: summary[a]["rate"] for a in ARMS}
    if g["new"] is None or g["old"] is None:
        print("\nHYPOTHESIS: INSUFFICIENT DATA — an arm had no valid trials "
              "(new={0}, old={1}).".format(summary["new"]["valid"], summary["old"]["valid"]))
    else:
        print("\nHYPOTHESIS green(new) > green(old): {0:.2f} > {1:.2f} -> {2}".format(
            g["new"], g["old"], "SUPPORTED" if g["new"] > g["old"] else "NOT supported"))
        if g["none"] is not None:
            print("Old-guard-vs-none green(old) vs green(none): {0:.2f} vs {1:.2f} -> {2}".format(
                g["old"], g["none"],
                "old ~ no-op" if abs(g["old"] - g["none"]) < 0.2 else
                ("old helps" if g["old"] > g["none"] else "old hurts")))
            print("New-guard-HELPS green(new) >= green(none): {0:.2f} >= {1:.2f} -> {2}".format(
                g["new"], g["none"], "yes" if g["new"] >= g["none"] else "no"))

    print("\nSLM cost: ${0:.4f} ({1} completions). NON-CIRCULAR: outcome scored by pytest, not an "
          "SLM. CAVEATS: single-shot SLM proxy (not the codex agent loop); ONE kwarg scenario; the "
          "new-vs-old delta bundles framing + more-explicit instructions (not framing in isolation). "
          "A codex-agent confirmation on more scenarios is the heavier follow-up.".format(
              total_cost, n * len(ARMS)))


if __name__ == "__main__":
    _n = int(sys.argv[1]) if len(sys.argv) > 1 else 12
    _model = sys.argv[2] if len(sys.argv) > 2 else "gpt-5.4-mini"
    run(_n, _model)
